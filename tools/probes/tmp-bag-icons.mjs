import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-gpu', '--use-gl=swiftshader'] })
const p = await b.newPage()
p.on('pageerror', e => console.log('PAGEERROR', e.message))
p.on('console', m => { const t = m.text(); if (/error|panic|Uncaught/i.test(t)) console.log('CONSOLE', m.type(), t.slice(0, 300)) })
p.on('response', r => { if (r.status() >= 400) console.log('HTTP', r.status(), r.url()) })
await p.setViewport({ width: 1260, height: 1000 })
await p.goto('http://127.0.0.1:8090/game/index.html#/map?renderer=canvas', { waitUntil: 'domcontentloaded' })
await p.waitForFunction(() => document.getElementById('hint').textContent.includes('点击地面行走'), { timeout: 90000 })
const box = await (await p.$('#wrap')).boundingBox()
console.log('点前 bagStatus:', await p.evaluate(() => { try { return M.player.bagStatus() } catch (e) { return 'err ' + e } }))
await p.mouse.click(box.x + 340, box.y + 620)
await new Promise(r => setTimeout(r, 4000))
console.log('点后 bagStatus:', await p.evaluate(() => { try { return M.player.bagStatus() } catch (e) { return 'err ' + e } }))
const lines = await p.evaluate(() => document.getElementById('log').textContent.split('\n'))
console.log('日志总行数 ' + lines.length + '，含"图标/格子/背包"的:')
console.log(lines.filter(l => /图标|格子|背包|bag/.test(l)).join('\n') || '(无)')
console.log('末尾 12 行:\n' + lines.slice(-12).join('\n'))
await b.close()
